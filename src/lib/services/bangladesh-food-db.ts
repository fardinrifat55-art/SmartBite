export type GroceryCategory =
  | "grains"
  | "protein_fish"
  | "protein_poultry_meat"
  | "eggs_dairy"
  | "lentils_legumes"
  | "vegetables"
  | "fruits"
  | "pantry_essentials";

export interface FoodItemDefinition {
  id: string;
  genericName: string;
  genericNameBn: string;
  category: GroceryCategory;
  standardUnit: "kg" | "litre" | "pcs" | "bunch";
  packSizes: { size: number; priceBdt: number }[]; // Package options in BDT
  defaultUnitPriceBdt: number; // e.g. BDT per standardUnit
  // Nutrition per 100g raw edible portion
  caloriesPer100g: number;
  proteinPer100g: number;
  carbsPer100g: number;
  fatPer100g: number;
  fiberPer100g: number;
  // Refuse conversion factor: edible portion fraction (0 to 1)
  edibleYield: number; // e.g. 0.65 for whole fish (bones/head removed), 0.88 for eggs (shell)
  isFallbackEstimate?: boolean;
  allergyTags?: string[]; // e.g. ["fish"], ["shellfish"], ["egg"], ["dairy"], ["gluten"]
  dietaryTags?: string[]; // e.g. ["halal", "vegetarian", "vegan"]
  seasonality?: "year_round" | "winter" | "summer" | "monsoon";
  recommendedDaysUsage?: number; // typical shelf life in days
}

